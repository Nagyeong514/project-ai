def main():
    print(f"영상 경로: {video_path}")
    print(f"결과 저장 폴더: {output_dir}")
    print(f"프롬프트 개수: {len(PROMPTS)}\n")

    model, processor = load_model_and_processor()

    for idx, (prompt_name, prompt_text) in enumerate(PROMPTS.items(), start=1):
        try:
            output_text = run_prompt(model, processor, prompt_name, prompt_text)
            save_result(idx, prompt_name, prompt_text, output_text)
        except Exception as e:
            print(f"에러 발생: {prompt_name}")
            print(str(e))
            traceback.print_exc()

    print("전체 완료!")

if __name__ == "__main__":
    main()
