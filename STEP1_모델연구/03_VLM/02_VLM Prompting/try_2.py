def save_result(idx, prompt_name, prompt_text, output_text):
    os.makedirs(output_dir, exist_ok=True)
    save_path = os.path.join(output_dir, f"final_{idx}_{prompt_name}.txt")
    with open(save_path, "w", encoding="utf-8") as f:
        f.write(f"[프롬프트 {idx}: {prompt_name}]\n")
        f.write("=" * 80 + "\n\n")
        f.write("[사용한 프롬프트]\n\n")
        f.write(prompt_text.strip() + "\n\n")
        f.write("=" * 80 + "\n\n")
        f.write("[모델 출력 결과]\n\n")
        f.write(output_text.strip() + "\n")
    print(f"저장 완료: {save_path}\n")

